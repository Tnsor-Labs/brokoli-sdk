"""``brokoli init`` and ``brokoli new pipeline``: create a project and its
pipelines from templates.

Both write only new files. Every target is checked first and nothing is
written if any already exists, so a half-created project never happens.
"""

from __future__ import annotations

import os
from pathlib import Path

import yaml

import brokoli
from brokoli.projects import (
    _PIPELINE_ID,
    _WORKSPACE_NAME,
    PIPELINE_FILE,
    PIPELINES_DIR,
    PROJECT_FILE,
    PROJECT_VERSION,
    ProjectError,
    find_project_root,
    load_config,
)

TEMPLATES = ("basic", "python")

_BASIC = '''"""{pipeline_id}: what this pipeline does, in a sentence or two.

Compile it with `brokoli compile --project`, check it with
`brokoli validate`.
"""

from brokoli import Pipeline, source_api, transform

with Pipeline(
    "{pipeline_id}",
    pipeline_id="{pipeline_id}",
    description="Fetch posts from an API and tidy the columns",
) as p:
    posts = source_api(
        "Fetch posts",
        url="https://jsonplaceholder.typicode.com/posts",
        timeout=15,
    )
    tidy = transform(
        "Tidy columns",
        rules=[{{"type": "rename_columns", "mapping": {{"userId": "user_id"}}}}],
    )
    posts >> tidy
'''

_PYTHON = '''"""{pipeline_id}: what this pipeline does, in a sentence or two.

The steps are Python functions. Code shared between pipelines goes in the
project's `shared/` package, which every pipeline.py can import.
"""

from brokoli import Pipeline, filter, map, source

with Pipeline(
    "{pipeline_id}",
    pipeline_id="{pipeline_id}",
    description="Fetch users, keep the ones with a company, add their email domain",
) as p:

    @source("Fetch users")
    def fetch_users():
        import json
        import urllib.request

        with urllib.request.urlopen("https://jsonplaceholder.typicode.com/users", timeout=10) as r:
            return json.loads(r.read())

    @filter
    def has_company(row):
        return bool(row.get("company", {{}}).get("name"))

    @map
    def add_domain(row):
        row["domain"] = row.get("email", "").split("@")[-1]
        return row

    fetch_users >> has_company >> add_domain
'''

_PIPELINE_TEMPLATES = {"basic": _BASIC, "python": _PYTHON}

_GITIGNORE = """__pycache__/
*.pyc
.venv/
.env
.brokoli/
build/
"""

_SHARED_INIT = '"""Code shared by every pipeline in this project."""\n'

_README = """# {name}

Brokoli pipelines as code. Each workspace has a folder, and each pipeline
is a folder holding its `pipeline.py`:

```
brokoli.yaml
workspaces/<workspace>/pipelines/<pipeline_id>/pipeline.py
shared/
```

Common commands, all offline unless they say otherwise:

| Command | Does |
|---|---|
| `brokoli new pipeline <id> --workspace <workspace>` | adds a pipeline from a template |
| `brokoli validate` | loads and checks every pipeline |
| `brokoli compile --project --out build` | writes each pipeline's IR and a manifest of digests |
| `brokoli plan --env <name>` | compares the project with a server (online) |
"""

_WORKFLOW = """# Checks every pull request and push: each pipeline loads, validates
# and compiles. Generated by `brokoli init`; edit freely.
name: brokoli
on:
  pull_request:
  push:
    branches: [main]
jobs:
  validate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - run: pip install "brokoli=={version}"
      - run: brokoli validate
      - run: brokoli compile --project --out build
"""


def _check_pipeline_id(pipeline_id: str) -> None:
    if not _PIPELINE_ID.match(pipeline_id):
        raise ProjectError(
            [
                f"{pipeline_id!r} is not a pipeline id: lowercase letters, digits and single "
                "hyphens, starting and ending with a letter or digit"
            ]
        )


def _write_all(files: "dict[Path, str]") -> list[Path]:
    """Write every file, or none if any exists."""
    existing = sorted(str(p) for p in files if p.exists())
    if existing:
        raise ProjectError([f"{p}: already exists; nothing was written" for p in existing])
    for path, body in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    return sorted(files)


def _pipeline_body(pipeline_id: str, template: str) -> str:
    if template not in _PIPELINE_TEMPLATES:
        raise ProjectError([f"unknown template {template!r}; choose one of {', '.join(TEMPLATES)}"])
    return _PIPELINE_TEMPLATES[template].format(pipeline_id=pipeline_id)


def init_project(
    directory: "str | os.PathLike[str]" = ".",
    workspace: str = "default",
    example: str = "example",
    template: str = "basic",
    workflow: bool = True,
) -> list[Path]:
    """Create a project in *directory*: brokoli.yaml, one workspace with an
    example pipeline, the shared package, a README, .gitignore, and (unless
    *workflow* is false) a GitHub Actions workflow that validates it."""
    root = Path(directory)
    if not _WORKSPACE_NAME.match(workspace):
        raise ProjectError(
            [f"{workspace!r} is not a workspace name: lowercase letters, digits, '-' and '_'"]
        )
    _check_pipeline_id(example)
    # Searched from the target even when it does not exist yet, so a new
    # folder inside an existing project is caught too.
    enclosing = find_project_root(root)
    if enclosing is not None and enclosing.resolve() != root.resolve():
        raise ProjectError([f"{root} is inside the project at {enclosing}; nothing was written"])

    ws_path = f"workspaces/{workspace}"
    config = {
        "version": PROJECT_VERSION,
        "workspaces": {workspace: {"path": ws_path}},
        "branches": {"main": {"production": True}},
    }
    header = (
        "# A Brokoli project. Each workspace maps to a folder; each pipeline is\n"
        f"# <folder>/{PIPELINES_DIR}/<pipeline_id>/{PIPELINE_FILE}.\n"
        "# Add `id: <server workspace id>` to a workspace for `brokoli plan`, and\n"
        "# named servers under `environments:` for --env.\n"
    )
    files = {
        root / PROJECT_FILE: header + yaml.safe_dump(config, sort_keys=False),
        root / ws_path / PIPELINES_DIR / example / PIPELINE_FILE: _pipeline_body(example, template),
        root / "shared" / "__init__.py": _SHARED_INIT,
        root / ".gitignore": _GITIGNORE,
        root / "README.md": _README.format(name=root.resolve().name),
    }
    if workflow:
        files[root / ".github" / "workflows" / "brokoli.yml"] = _WORKFLOW.format(
            version=brokoli.__version__
        )
    return _write_all(files)


def new_pipeline(
    pipeline_id: str,
    workspace: "str | None" = None,
    template: str = "basic",
    start: "str | os.PathLike[str]" = ".",
) -> Path:
    """Add a pipeline folder to the project at or above *start*. The
    workspace may be omitted when the project has exactly one."""
    _check_pipeline_id(pipeline_id)
    root = find_project_root(start)
    if root is None:
        raise ProjectError(["no project here (create one with: brokoli init)"])
    config = load_config(root)
    if workspace is None:
        if len(config.workspaces) != 1:
            names = ", ".join(sorted(config.workspaces))
            raise ProjectError([f"choose a workspace with --workspace ({names})"])
        workspace = next(iter(config.workspaces))
    if workspace not in config.workspaces:
        names = ", ".join(sorted(config.workspaces))
        raise ProjectError([f"no workspace {workspace!r} in {PROJECT_FILE} (have: {names})"])
    folder = root / config.workspaces[workspace].path / PIPELINES_DIR / pipeline_id
    target = folder / PIPELINE_FILE
    if folder.exists():
        raise ProjectError([f"{folder}: already exists; nothing was written"])
    _write_all({target: _pipeline_body(pipeline_id, template)})
    return target
